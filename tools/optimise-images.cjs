/*
 * Image optimiser for the Divine site.
 *
 * Usage (from the site folder):
 *   npm install --prefix tools sharp
 *   node tools/optimise-images.cjs
 *
 * Reads every .jpg/.jpeg/.png in images/originals/ and writes, into images/:
 *   name.jpg                 – optimised fallback at the largest size
 *   name-{w}.webp / .jpg     – responsive variants (600 / 800 / 1000 / 1600, capped at the source width)
 * Then regenerates js/photos.js, which tells main.js which responsive sizes exist.
 * Also builds og-image.jpg (1200×630, from the hero) and the PNG app icons from favicon.svg.
 */
const fs = require("fs");
const path = require("path");
const sharp = require("sharp");

const root = path.resolve(__dirname, "..");
const srcDir = path.join(root, "images", "originals");
const outDir = path.join(root, "images");
const TARGETS = [600, 800, 1000, 1600];

(async () => {
  const registry = {};
  // logo-* files are handled separately below.
  const files = fs.readdirSync(srcDir).filter((f) => /\.(jpe?g|png)$/i.test(f) && !f.startsWith("logo-"));

  for (const file of files) {
    const name = file.replace(/\.(jpe?g|png)$/i, "");
    const input = sharp(path.join(srcDir, file)).rotate();
    const meta = await input.metadata();
    const maxW = Math.min(meta.width, 1600);
    const widths = [...new Set([...TARGETS.filter((w) => w < maxW), maxW])];

    for (const w of widths) {
      const resized = sharp(path.join(srcDir, file)).rotate().resize({ width: w });
      await resized.clone().webp({ quality: 78 }).toFile(path.join(outDir, `${name}-${w}.webp`));
      await resized.clone().jpeg({ quality: 80, mozjpeg: true }).toFile(path.join(outDir, `${name}-${w}.jpg`));
    }
    await sharp(path.join(srcDir, file)).rotate().resize({ width: maxW })
      .jpeg({ quality: 80, mozjpeg: true }).toFile(path.join(outDir, `${name}.jpg`));

    const height = Math.round((meta.height / meta.width) * maxW);
    registry[`images/${name}.jpg`] = { width: maxW, height, widths };
    console.log(`✓ ${name}  ${widths.join(", ")}w`);
  }

  const hero = path.join(srcDir, "hero-candlelit-tablescape.jpg");
  if (fs.existsSync(hero)) {
    // Crop a 1200:630 band positioned 30% down the photo (same framing as the hero's object-position).
    const { width: hw, height: hh } = await sharp(hero).rotate().metadata();
    const cropH = Math.round((hw * 630) / 1200);
    await sharp(hero).rotate()
      .extract({ left: 0, top: Math.round((hh - cropH) * 0.3), width: hw, height: cropH })
      .resize(1200, 630)
      .jpeg({ quality: 82, mozjpeg: true })
      .toFile(path.join(outDir, "og-image.jpg"));
    console.log("✓ og-image.jpg (1200×630)");
  }

  // Logo: cut the round badge out of its dark square background, then build the favicon + app icons from it.
  const logoSrc = path.join(srcDir, "logo-source.jpg");
  if (fs.existsSync(logoSrc)) {
    const LOGO = { left: 16, top: 19, size: 160 }; // the white circle inside logo-source.jpg
    const r = LOGO.size / 2;
    const mask = Buffer.from(
      `<svg width="${LOGO.size}" height="${LOGO.size}"><circle cx="${r}" cy="${r}" r="${r - 0.5}" fill="#fff"/></svg>`
    );
    const circle = await sharp(logoSrc)
      .extract({ left: LOGO.left, top: LOGO.top, width: LOGO.size, height: LOGO.size })
      .composite([{ input: mask, blend: "dest-in" }])
      .png()
      .toBuffer();
    await sharp(circle).toFile(path.join(outDir, "logo.png"));
    await sharp(circle).webp({ quality: 90 }).toFile(path.join(outDir, "logo.webp"));
    await sharp(circle).resize(64, 64).png().toFile(path.join(root, "favicon.png"));
    // App icons need an opaque square: badge centred on white.
    for (const [file, size] of [["apple-touch-icon.png", 180], ["icon-192.png", 192], ["icon-512.png", 512]]) {
      const inner = Math.round(size * 0.92);
      await sharp({ create: { width: size, height: size, channels: 4, background: "#ffffff" } })
        .composite([{ input: await sharp(circle).resize(inner, inner).toBuffer(), gravity: "centre" }])
        .png()
        .toFile(path.join(root, file));
    }
    console.log("✓ logo + favicon + app icons");
  }

  const js =
    "// Generated by tools/optimise-images.cjs. Do not edit by hand.\n" +
    "// Lists the responsive sizes that exist for each photo, so main.js can build <picture> srcsets.\n" +
    `const PHOTOS = ${JSON.stringify(registry, null, 2)};\n`;
  fs.writeFileSync(path.join(root, "js", "photos.js"), js);
  console.log("✓ js/photos.js");
})().catch((err) => {
  console.error(err);
  process.exit(1);
});
